"""Generate a closed, AOT-safe RPC map from the committed capability contracts.
No runtime reflection, method-name execution or generated assembly loading.
"""
from pathlib import Path
import re,json
ROOT=Path(__file__).resolve().parents[2]
USINGS='''using System.Text.Json;
using Echo.Contracts.Library;
using Echo.Contracts.Scanning;
using Echo.Contracts.Remote;
using Echo.Contracts.Podcast;
using Echo.Contracts.Radio;
using Echo.Contracts.Lyrics;
using Echo.Contracts.Tasks;
using Echo.Application.Playback;
using Echo.Playback;
using Echo.Bridge;
'''
def write(path,text):
 p=ROOT/path;p.parent.mkdir(parents=True,exist_ok=True);p.write_text(text)
def split_args(args):
 result=[];start=0;level=0
 for i,ch in enumerate(args):
  if ch in '<([':level+=1
  elif ch in '>)]':level-=1
  elif ch==',' and level==0:result.append(args[start:i].strip());start=i+1
 if args.strip():result.append(args[start:].strip())
 return result
def parse(ret,name,args):
 args=re.sub(r'\s+',' ',args)
 parameters=[]
 for arg in split_args(args):
  m=re.fullmatch(r'(.+?) (\w+)(?: = (.*))?',arg)
  if not m:raise ValueError(arg)
  parameters.append(m.groups())
 return dict(ret=ret,name=name,args=args,params=parameters)
entries=[]
# Every callable operation is listed statically. Lifecycle, event and progress members have dedicated adapters.
for group,files in [('Playback',[ROOT/'src/Echo.Playback.Contracts/IPlaybackSession.cs']),('Library',sorted((ROOT/'src/Echo.Core/Library').glob('LibraryCore*.cs'))),('Podcasts',[ROOT/'src/Echo.Contracts/Podcast/IPodcastLibrary.cs'])]:
 for file in files:
  text=file.read_text()
  pat=r'^    (?:public (?:async )?)?(Task(?:<[^\n]+?>)?) (\w+)\((.*?)\)\s*(?:=>|\{|;)'
  for match in re.finditer(pat,text,re.M|re.S):
   op=parse(*match.groups())
   if any('IProgress<' in x[0] for x in op['params']):continue
   op['group']=group
   # Overloads receive explicit protocol names, not runtime overload resolution.
   suffix='Json' if op['name']=='ConfigureOutputAsync' and op['params'][0][0]=='JsonElement' else ''
   op['key']=group.lower()+'.'+op['name']+suffix
   op['dto']=group+op['name'].removesuffix('Async')+suffix+'Request'
   op['data']=[p for p in op['params'] if p[0]!='CancellationToken']
   entries.append(op)
manifest=json.loads((ROOT/'tools/architecture/core-rpc-capabilities.json').read_text())
approved={entry['method']:entry for entry in manifest['operations']}
entries=[op for op in entries if op['key'] in approved]
for op in entries:
 expected=approved[op['key']]
 actual={'method':op['key'],'result':op['ret'],'parameters':[list(parameter) for parameter in op['params']]}
 if actual!=expected:raise ValueError('Review the protocol version and capability manifest before changing '+op['key'])
if {op['key'] for op in entries}!=set(approved):raise ValueError('An approved RPC capability disappeared; review compatibility')
keys=[op['key'] for op in entries]
assert len(keys)==len(set(keys)),[x for x in keys if keys.count(x)>1]
# Request records remain small and source-generated; IEnumerable is materialized with a hard boundary at the client.
records=[];contexts=set(['CoreMessage','CoreHello','CoreWelcome','CorePlaybackFrame','CoreFailure','CoreTaskRequest','CoreTaskSnapshot','CoreTaskStart','CoreTaskCancel','CoreProgress','CoreSettingsRequest','CoreRemoteRequest','CoreRadioState','CoreRadioWrite','CoreReadResource','CoreBytes','CoreBroadcastRequest','CoreMaintenanceRequest','CoreDiagnostic','CoreEndpointInfo','CoreTaskSnapshot[]','RemoteConnection[]','RadioStation[]','FeatureSetting','Echo.Contracts.Settings.FeatureSetting','Echo.Contracts.Settings.DesktopPreferences'])
contexts.discard('FeatureSetting')
contexts.update(['Echo.Contracts.Backup.BackupManifest','Echo.Contracts.Backup.BackupSchedule','Dictionary<string, Echo.Contracts.Settings.FeatureSetting>','CoreRadioMetadata','CoreRadioSearch','CoreBroadcastState','RadioDirectoryResult','RadioStreamInfo','BridgeCommand','BridgeState','DlnaRenderer[]','CoreAccessoryRequest','string[]','JsonElement?','CoreSleepRequest','BackgroundWorkKind','BackgroundAdmissionSnapshot','LyricsText','AttachmentPage','RemoteConnection','RemoteDirectoryPage','RemoteMediaSource','bool','string','int','long','double'])
for op in entries:
 fields=[]
 for typ,name,default in op['data']:
  typ=typ.replace('IEnumerable<','IReadOnlyList<')
  fields.append(f'{typ} {name[0].upper()+name[1:]}')
 records.append(f'public sealed record {op["dto"]}('+', '.join(fields)+');')
 contexts.add(op['dto'])
 if op['ret']!='Task':contexts.add(op['ret'][5:-1].removesuffix('?'))
write('src/Echo.Core.Contracts/Generated/Requests.g.cs','// <auto-generated by tools/architecture/generate_core_rpc.py />\n#nullable enable\n'+USINGS+'\nnamespace Echo.Core.Contracts;\n\n'+'\n'.join(records)+'\n')
write('src/Echo.Core.Contracts/Generated/CoreJsonContext.g.cs','// <auto-generated by tools/architecture/generate_core_rpc.py />\n#nullable enable\n'+USINGS+'using System.Text.Json.Serialization;\n\nnamespace Echo.Core.Contracts;\n\n[JsonSourceGenerationOptions(PropertyNamingPolicy = JsonKnownNamingPolicy.CamelCase)]\n'+''.join(f'[JsonSerializable(typeof({t}))]\n' for t in sorted(contexts))+'public partial class CoreJsonContext : JsonSerializerContext;\n')
for group,typ,owner in [('Playback','CorePlaybackClient','session'),('Library','CoreLibraryClient','library'),('Podcasts','CorePodcastClient','podcasts')]:
 methods=[];cases=[]
 for op in [x for x in entries if x['group']==group]:
  values=[]
  for t,n,d in op['data']:
   values.append(n+'.Take(1001).ToArray()' if t.startswith('IEnumerable<') else n)
  ct=next((n for t,n,d in op['params'] if t=='CancellationToken'),'CancellationToken.None')
  request=f'new {op["dto"]}('+', '.join(values)+')'
  result=op['ret'][5:-1] if op['ret']!='Task' else None
  call=f'wire.CallAsync{f"<{result}>" if result else ""}("{op["key"]}", CoreJson.Value({request}), {ct})'
  methods.append(f'    public {op["ret"]} {op["name"]}({op["args"]}) => {call};')
  argvalues=[ct if t=='CancellationToken' else 'args.'+n[0].upper()+n[1:] for t,n,d in op['params']]
  argvalues=[('token' if t=='CancellationToken' else v) for (t,n,d),v in zip(op['params'],argvalues)]
  invoke=f'await {owner}.{op["name"]}('+', '.join(argvalues)+').ConfigureAwait(false)'
  resultline=f'return CoreJson.Value({invoke});' if result else f'{invoke}; return CoreJson.Empty;'
  cases.append(f'            case "{op["key"]}":\n            {{\n                var args = CoreJson.Read<{op["dto"]}>(payload);\n                {resultline}\n            }}')
 write(f'src/Echo.Core.Client/Generated/{typ}.g.cs','// <auto-generated by tools/architecture/generate_core_rpc.py />\n#nullable enable\n'+USINGS+'using Echo.Core.Contracts;\n\nnamespace Echo.Core.Client;\n\npublic sealed partial class '+typ+'\n{\n'+'\n'.join(methods)+'\n}\n')
 write(f'src/Echo.Core/Hosting/Generated/{group}Dispatch.g.cs','// <auto-generated by tools/architecture/generate_core_rpc.py />\n#nullable enable\n'+USINGS+'using Echo.Core.Contracts;\n\nnamespace Echo.Core.Hosting;\n\ninternal sealed partial class CoreDispatch\n{\n'+f'    private async Task<JsonElement?> Dispatch{group}Async(string method, JsonElement payload, CancellationToken token)\n    {{\n        var {owner} = runtime.'+{'Playback':'Playback.LocalZone.Session','Library':'Library','Podcasts':'Podcasts!'}[group]+';\n        switch (method)\n        {\n'+'\n'.join(cases)+'\n            default: return null;\n        }\n    }\n}\n')
print('Static operations:',len(entries))
